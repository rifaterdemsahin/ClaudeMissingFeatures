"""Generate EDL.md (edit decision list + how we worked) from the real edit data. Run: python3 -I scripts/build_edl.py
Sources: remotion/src/overlays.json, cuts.json, assets/base_info.json, assets/edl_decisions.json, export_map.js, assets/repeats.txt"""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
J = lambda p: json.load(open(ROOT / p))
ov, cuts, dec = J("remotion/src/overlays.json"), J("remotion/src/cuts.json"), J("assets/edl_decisions.json")
base = J("assets/base_info.json") if (ROOT / "assets/base_info.json").exists() else None
_m = re.search(r"=\s*(\{.*\});", (ROOT / "export_map.js").read_text()) if (ROOT / "export_map.js").exists() else None
M = json.loads(_m.group(1)) if _m else None
def out(t):
    if not M: return t
    for a, b, r, m, o in M["segs"]:
        if a <= t < b + 1e-9: return o + (t - a) / r
    return None
tc = lambda s: "–" if s is None else f"{int(s // 60)}:{s % 60:05.2f}"
rows, n = [], 0
def add(kind, a, b, what, why, status="done", src=True):
    global n; n += 1; oa, ob = (out(a), out(b - 0.001)) if src else (a, b)
    rows.append(f"| {n} | {kind} | {tc(a) if src else '–'} | {tc(b) if src else '–'} | {tc(oa)} | {tc(ob)} | {b - a:.1f} | {what} | {why} | {status} |")
ic = ov["intro_card"]
if ic["to"] > ic["from"]: add("INTRO", ic["from"], ic["to"], "Title card (Claude Whiteboard MISSING?)", "hides the OBS Studio window at the start; extended by 2 s on request")
for s in ov["slides"]: add("SLIDE", s["from"], s["to"], f"“{s['title']}”: " + "; ".join(s["bullets"])[:110], "covers a personal or distracting window (IBM chat, Grok Bot, family photo widget); narration kept")
rule = {"A": "chat-title list in the app sidebar", "B": "sensitive words", "C": "mini sidebar inside the pasted screenshot"}
for r in "ABC":
    bs = [b for b in ov["blurs"] if b["rule"] == r]
    if bs: add("BLUR", min(b["from"] for b in bs), max(b["to"] for b in bs), f"{len(bs)} frosted boxes: {rule[r]}", "private titles and names; boxes generated from OCR (build_blurs.py)")
for im in ov.get("images", []): add("IMAGE", im["from"], im["to"], f"Picture {im['src']}: \"{im.get('caption', '')} {im.get('caption2', '')}\" with a box and an arrow", im.get("why", "owner image"))
for s in ov["speedups"]: add("SPEED", s["from"], s["to"], f"{s['rate']}x" + (", muted, captions hidden" if s.get("mute") else ""), s.get("why", ""))
for af in (J("assets/audio_fixes.json") if (ROOT / "assets/audio_fixes.json").exists() else []): add("AUDIO", af["from"], af["to"], af["what"], af["why"])
for c in cuts: add("CUT", c[0], c[1], "Removed", "see decisions")
if not cuts: rows.append("| – | CUT | – | – | – | – | 0 | none applied | candidates below; nothing is cut until the owner decides | open |")
tot = M["total"] if M else 0; t = tot
for p in ov.get("outro", []):
    add("OUTRO", t, t + p["seconds"], f"{p['title']}" + (" (Delivery Pilot on Skool)" if p["kind"] == "cta" else ""), "owner request: end with a summary, then the community call to action", src=False); rows[-1] = rows[-1].replace("| – | – | " + tc(t), f"| – | – | {tc(t)}", 1); t += p["seconds"]
log = "\n".join(f"| {d['id']} | {d['when']} | {d['who']} | {d['said']} | {d['decision']} | `{d['how']}` | {d['check']} |" for d in dec)
cand = (ROOT / "assets/repeats.txt")
cand_txt = "\n".join("- " + x for x in cand.read_text().splitlines() if x and not x.startswith("#"))[:1800] if cand.exists() else "- run `scripts/find_repeats.py`"
src = ""
if base: src = f"- Source: {len(base['clips'])} screen recordings + 1 voice WAV ({base['voice']}); voice starts at {base['voice_start']} s; base video {base['total_s']} s ({base['frames']} frames, 1920x1080, 30 fps).\n" + "".join(f"  - {c['clip']}: offset {c['offset']} s, kept {c['keep']} s, sync confidence {c['conf']}\n" for c in base["clips"])
md = f"""---
published: false
---
# EDL: edit decision list and how we worked

{src}- Export: {tc(tot)} of footage plus a {sum(p['seconds'] for p in ov.get('outro', []))} s ending = {tc(tot + sum(p['seconds'] for p in ov.get('outro', [])))}.
- **Timecodes:** `m:ss.ss`. *Source* = the original synced video (player: Original). *Export* = after the edits (player: Latest export; the typing speed-up and the ending shift later times). The owner's notes use `[export m:ss]`; `04:17:28` style timecodes are `mm:ss:ff` at 30 fps.
- Generated by `scripts/build_edl.py` from `remotion/src/overlays.json`, `cuts.json` and `assets/edl_decisions.json`. Edit those, not this file.

## 1. Edit decision list

| # | Type | Source in | Source out | Export in | Export out | Sec | What | Why / request | Status |
|---|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + f"""

## 2. How we worked

1. **Prepare locally.** The MacBook syncs the clips to the voice, renders the 1080p base, transcribes with Whisper, OCRs the screen (Apple Vision) and writes a one-page `REPORT.md`. Claude reads that text, not frames (see the Architecture page).
2. **Owner reviews in the player.** Original vs Latest export (or side by side), with J/K/L speed keys. Notes are timestamped `[orig m:ss]` / `[export m:ss]` and pasted back.
3. **Interpret, then decide.** Each note is mapped to source time (export time + the time saved by speed-ups), checked against the data (transcript, OCR, audio analysis, one still), and turned into an entry in `overlays.json`, `cuts.json` or an audio step. If the literal request would damage the video (cutting three minutes to remove a hoover), do the smaller fix that meets the goal and say so.
4. **Cover before cut.** Personal windows are covered with slides so the voice track stays whole; only dead or repeated parts are candidates for cuts, and nothing is cut until the owner decides.
5. **Re-render once.** All pending edits go into one export (about 29 min), never one render per note.
6. **Verify by script.** `verify_export.py` OCRs the finished export for leaked text; stills confirm the look; numbers confirm audio. Anything found becomes a new decision (see #6).
7. **Record it here.** Every request, interpretation, implementation and check is a row in the decision log, so the next video starts from these rules.

## 3. Decision log (requests and how each was handled)

| # | When | Who | Said | Decision | Implemented in | Checked by |
|---|---|---|---|---|---|---|
{log}

## 4. Cut candidates (nothing applied yet)

{cand_txt}

## 5. Rules learned for the next EDL

- Convert every owner timecode to source time first: `source = export + time saved by earlier speed-ups`.
- Measure, do not guess: spectrogram and noise floor for audio problems, OCR for text, one still for a look.
- Prefer a fix that keeps content (cover, blur, denoise, speed up) over a cut; state clearly when the request was met another way.
- Pad every generated box or slide at its edges: sampling every 2 s can miss a second.
- Keep hard cuts (no fades) unless the owner asks for transitions.
"""
(ROOT / "EDL.md").write_text(md); print("EDL.md:", len(rows), "decisions rows,", len(dec), "log entries")
